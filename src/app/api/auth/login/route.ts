import { z } from "zod";
import { cookies } from "next/headers";
import { authenticate, EmailSchema } from "@/lib/identity";
import { setSessionCookie } from "@/lib/auth";
import { LANG_COOKIE } from "@/lib/lang";
import { handler, ok, fail, parseBody } from "@/lib/api";
import { rateLimit, getClientIp } from "@/lib/rate-limit";
const schema = z.object({ email: EmailSchema, password: z.string().min(1).max(200) }).strict();
export const POST = handler(async (req: Request) => {
  const ipLimit = await rateLimit(`login:ip:${getClientIp(req)}`, 10);
  if (!ipLimit.ok) return fail(429, "Too many attempts", { retryAfterSec: ipLimit.retryAfterSec });
  const input = await parseBody(req, schema);
  const emailLimit = await rateLimit(`login:email:${input.email}`, 10);
  if (!emailLimit.ok) return fail(429, "Too many attempts", { retryAfterSec: emailLimit.retryAfterSec });
  const user = await authenticate(input.email, input.password);
  if (!user) return fail(401, "Invalid email or password");
  await setSessionCookie({ userId: user.id, role: user.role, name: user.name, email: user.email, sessionVersion: user.sessionVersion, passwordHash: user.passwordHash });
  (await cookies()).set({ name: LANG_COOKIE, value: user.language === "en" ? "en" : "ar", path: "/", maxAge: 31536000, sameSite: "lax", secure: process.env.NODE_ENV === "production" });
  return ok({ user: { id: user.id, name: user.name, role: user.role, language: user.language } });
});
